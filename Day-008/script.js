// Day 8: String manipulation: length, slice, trim, toupperCase, replace (Reference: W3Schools Strings)
let myString = "  Hello JS World  ";
console.log("Original string:", myString);
console.log("Length:", myString.length);
console.log("Trimmed:", myString.trim());
console.log("Slice (2, 7):", myString.slice(2, 7));
console.log("Uppercase:", myString.toUpperCase());
console.log("Replace:", myString.replace("JS", "JavaScript"));